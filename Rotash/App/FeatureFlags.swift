import Foundation

/// 検証中でまだ確定していない仕様をまとめておく場所。
/// UI・ロジックはこのフラグだけを見て判断するので、値を変えるだけで挙動を戻せる。
enum RotashFeatureFlags {
    /// 撮影済みの枠を撮り直せるかどうか。
    /// 現在は仮で false（撮ったら確定）。
    /// true に戻すと AppViewModel.canShoot 経由で ThisWeekView 側のコードは
    /// 変更なしで撮り直し（SHOOT / RETAKE 表示・ライブビュー優先表示を含む）が復活する。
    static let allowRetake = false

    /// 撮った直後だけ、撮り直しを自由にできる秒数。0 にすると撮り直しは一切できない（従来どおり）。
    ///
    /// 目ブレ・指かぶりなどの「事故」を救うためのもの。起点は **その日の最初の1枚** なので、
    /// 何度撮り直しても延びない。30秒では何十枚も撮り比べられないので、
    /// 残るのは「ベストショット」ではなく「その日の1枚」のまま。
    /// 撮り直せるのは撮った本人だけ（`AppViewModel.canRetake`）。
    static let retakeWindowSeconds: TimeInterval = 30

    /// 当番日を過ぎた枠を、後から撮って埋められるようにするか。
    /// 現在は false。撮られないまま終わった日は No Shot として作品に残る
    /// （「その日には写真がなかった」という状態そのものを作品の一部として扱う）。
    /// true にすると、過去の自分の当番日をあとから撮って埋められるようになる。
    static let allowCatchUpShooting = false

    /// 共有画像の形。
    ///
    /// いまは `.screen`（撮影画面と同じ横長の7分割）。
    /// 受け取った人が画像とアプリを結びつけられることを、写真の写る量より優先している。
    ///
    /// 「縦長の枠に撮るより横長7分割のほうがよい」というフィードバックが固まったら、
    /// `.story`（9:16 の縦）に変える。描画はどちらも同じ手続きなので、この1行で入れ替わる。
    static let shareCardFormat: ShareCardFormat = .screen

    /// 縦持ちで撮れるようにするか（試験中）。
    ///
    /// 7分割の枠は縦に細長いので、スマホを横にして撮ると写真の横幅を8割捨てることになる。
    /// 撮る瞬間だけ縦にすれば、枠とカメラの向きがそろい、**曲げずに**横も縦も約1.3倍広く写る。
    /// true のとき、担当日には縦のホームに「縦のまま撮る」が出る（横にして撮る方法もそのまま使える）。
    static let allowsPortraitShooting = true

    /// 外カメで超広角（0.5倍）レンズを使うか。無い機種では自動で普通の広角になる。
    /// 7分割の枠は細く、普通の広角では「自撮り以外に撮るものがない」が起きやすいため。
    /// false に戻すと、これまでどおりの 1倍カメラになる。
    static let prefersUltraWideBackCamera = true

    /// 内カメを、いちばん広く写る状態で使うか。
    /// - センターフレーム対応の iPad などは、内カメそのものが超広角なのでそれを使う
    /// - iPhone の内カメは、センサーを最も広く読むモード（純正カメラの矢印ボタンで広がる状態）にする
    /// false に戻すと、これまでどおり既定の読み出し（`.photo` プリセットまかせ）になる。
    static let prefersWidestFrontCamera = true

    /// Rotash レンズ（疑似広角）の広げ具合（`RotashLens`）。枠に、普通の何倍の範囲を収めるか。
    ///
    /// 1.0 で従来どおり（写真の中央を切り出すだけ）。1.3 なら縦にも横にも 1.3 倍の範囲が入り、
    /// 真ん中の形は曲がらない。足りない上下の端（空・天井・床など）だけが縦に伸びる。
    /// 写真ファイルそのものは加工しない（表示のときだけかける）ので、
    /// ここを 1.0 に戻せば、これまで撮った写真も含めて元の見え方に戻る。
    /// 1.45 より大きくしても、上下が破綻しないよう 1.45 で止まる（`RotashLens.maxVerticalZoom`）。
    ///
    /// 検証用ビルドでは、設定画面の「レンズ」から端末ごとに切り替えて見くらべられる。
    static let lensWidening: Double = 1.3

    /// 内カメで撮った写真の広げ具合（`RotashLens.Style.faceSafeWide`）。枠に、普通の何倍の横幅を入れるか。
    /// 顔は形を変えずに 1.45 倍まで縮め（足りない高さは髪の上・服のあたりを縦に伸ばす）、
    /// それを超えるぶんは顔より外の左右の端に押し込む。2.0 なら左右の端が約 1/2 の幅になる。
    /// 写真の横幅を全部は使わない（縦持ちでも 8 割ほど。全部だと端が潰れすぎて釣り合わない）。
    /// 1.0 で従来どおり。検証用ビルドでは設定画面の「内カメ」で切り替えられる。
    static let frontLensWidening: Double = 2.0

    /// 検証中のビルドかどうか。TestFlight と開発ビルドで true、App Store 版では false。
    ///
    /// 「動きを確かめるための仕掛け」は、確かめている間しか要らない。
    /// 出したまま公開すると、説明の要るものが増えるだけでなく、
    /// 自由撮影モードのように **競合を自分から作り出す** ものまで届いてしまう。
    ///
    /// TestFlight のアプリは Sandbox のレシートを持つので、それで見分ける。
    /// 判定に失敗したときは「本番」に倒す（検証用の仕掛けを誤って出さない方に倒す）。
    static var isTestBuild: Bool {
        #if DEBUG
        return true
        #else
        return Bundle.main.appStoreReceiptURL?.lastPathComponent == "sandboxReceipt"
        #endif
    }
}
