import Foundation

/// 検証中でまだ確定していない仕様をまとめておく場所。
/// UI・ロジックはこのフラグだけを見て判断するので、値を変えるだけで挙動を戻せる。
enum RotashFeatureFlags {
    /// 撮影済みの枠を撮り直せるかどうか。
    /// 現在は仮で false（撮ったら確定）。
    /// true に戻すと AppViewModel.canShoot 経由で ThisWeekView 側のコードは
    /// 変更なしで撮り直し（SHOOT / RETAKE 表示・ライブビュー優先表示を含む）が復活する。
    static let allowRetake = false

    /// 撮った直後だけ、撮り直しを自由にできる秒数。0 にすると撮り直しは一切できない（従来どおり）。
    ///
    /// 目ブレ・指かぶりなどの「事故」を救うためのもの。起点は **その日の最初の1枚** なので、
    /// 何度撮り直しても延びない。30秒では何十枚も撮り比べられないので、
    /// 残るのは「ベストショット」ではなく「その日の1枚」のまま。
    /// 撮り直せるのは撮った本人だけ（`AppViewModel.canRetake`）。
    static let retakeWindowSeconds: TimeInterval = 30

    /// 当番日を過ぎた枠を、後から撮って埋められるようにするか。
    /// 現在は false。撮られないまま終わった日は No Shot として作品に残る
    /// （「その日には写真がなかった」という状態そのものを作品の一部として扱う）。
    /// true にすると、過去の自分の当番日をあとから撮って埋められるようになる。
    static let allowCatchUpShooting = false

    /// 共有画像の形。
    ///
    /// いまは `.story`（7枚を横長の帯にして縦に積む。写真がまっすぐ立ち、写る量も多い）。
    /// ストーリーで首をかしげずに見られることを、アプリの画面と同じ並びであることより優先した（2026-10-15）。
    ///
    /// `.screen`（撮影画面の7分割を90度倒したもの）に戻すなら、この1行を変える。描画はどちらも同じ手続き。
    static let shareCardFormat: ShareCardFormat = .story

    /// 共有画像の各枠の下に、裏（撮るときシャッター側に映っていた方）を丸で添えるか。
    ///
    /// ストーリーは指で送られていくので、裏返る動きや2枚目は見てもらえないことがある。
    /// 1枚目で両方のカメラが見えていないと、片方だけでは情報が少なく、止まってもらえない。
    /// 曜日は枠の上、丸は枠の下に置き、写真の主役が来る真ん中は空けておく（アプリの画面も同じ並び）。
    /// false にすると表だけになる。
    static let shareShowsReverseBadge = true


    /// 外カメで超広角（0.5倍）レンズを使うか。無い機種では自動で普通の広角になる。
    /// 7分割の枠は細く、普通の広角では「自撮り以外に撮るものがない」が起きやすいため。
    /// false に戻すと、これまでどおりの 1倍カメラになる。
    static let prefersUltraWideBackCamera = true

    /// 招待リンクを Web のリンク（`https://rotash-f83a4.web.app/j/ABC123`）で送るか。
    ///
    /// アプリが入っていない人にも届く（Web のページでコードをコピーして、アプリを入れてから貼り付ける）。
    /// **Firebase Hosting に `web/` を公開してから true にする**（`docs/FIREBASE_SETUP.md`）。
    /// 公開する前に true にすると、押した人に「ページが見つかりません」が出る。
    /// false のあいだは、これまでどおり `rotash://join/ABC123`（アプリが入っている人だけに効く）。
    static let usesWebInviteLinks = false
}
